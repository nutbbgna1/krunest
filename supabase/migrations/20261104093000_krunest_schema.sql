-- Krunest application schema for Supabase Postgres.
-- Run in Supabase SQL Editor before `npm run supabase:sync`.
-- The Express backend uses a server-only Secret key. Public clients receive no direct table policies.

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  email text unique not null, password_hash text not null, name text not null,
  organization text default '', role text not null default 'member',
  email_verified integer not null default 0, two_factor_secret text,
  two_factor_enabled integer default 0, notification_email integer default 1,
  created_at timestamptz default now(), updated_at timestamptz default now()
);

create table if not exists public.sessions (
  id text primary key, user_id bigint not null references public.users(id) on delete cascade,
  csrf_token text not null, expires_at timestamptz not null,
  last_seen_at timestamptz default now(), created_at timestamptz default now()
);

create table if not exists public.tokens (
  token text primary key, user_id bigint not null references public.users(id) on delete cascade,
  type text not null, expires_at timestamptz not null, used_at timestamptz
);

create table if not exists public.login_attempts (
  key text primary key, count integer default 0, reset_at timestamptz not null
);

create table if not exists public.programs (
  id text primary key, name text not null, thai_name text not null,
  price integer not null, active integer default 1
);

create table if not exists public.plans (
  id text primary key, name text not null, monthly_price integer not null,
  yearly_price integer not null, program_limit integer not null, active integer default 1
);

create table if not exists public.subscriptions (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  plan_id text not null references public.plans(id), billing_cycle text default 'monthly',
  status text default 'active', starts_at timestamptz default now(),
  ends_at timestamptz, trial_ends_at timestamptz
);

create table if not exists public.entitlements (
  user_id bigint not null references public.users(id) on delete cascade,
  program_id text not null references public.programs(id), access_level text default 'full',
  source text not null, expires_at timestamptz, created_at timestamptz default now(),
  primary key (user_id, program_id)
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  reference text unique not null, user_id bigint not null references public.users(id) on delete cascade,
  target_type text not null, target_id text not null, amount integer not null,
  status text default 'pending', expires_at timestamptz not null,
  reviewed_by bigint references public.users(id), reviewed_at timestamptz,
  reject_reason text, created_at timestamptz default now()
);

create table if not exists public.payment_slips (
  id bigint generated by default as identity primary key,
  order_id bigint unique not null references public.orders(id) on delete cascade,
  file_name text not null, mime_type text not null, size integer not null,
  data text not null, uploaded_at timestamptz default now()
);

create table if not exists public.receipts (
  id bigint generated by default as identity primary key,
  receipt_no text unique not null, order_id bigint unique not null references public.orders(id),
  issued_at timestamptz default now()
);

create table if not exists public.teams (
  id bigint generated by default as identity primary key, name text not null,
  owner_id bigint not null references public.users(id), seat_limit integer default 5,
  created_at timestamptz default now()
);

create table if not exists public.team_members (
  team_id bigint not null references public.teams(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  team_role text default 'member', joined_at timestamptz default now(),
  primary key (team_id, user_id)
);

create table if not exists public.team_invites (
  token text primary key, team_id bigint not null references public.teams(id) on delete cascade,
  email text, expires_at timestamptz not null, used_at timestamptz
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  title text not null, message text not null, read_at timestamptz,
  created_at timestamptz default now()
);

create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  title text not null, message text not null, active integer default 1,
  created_by bigint references public.users(id), created_at timestamptz default now()
);

create table if not exists public.email_queue (
  id bigint generated by default as identity primary key,
  dedupe_key text unique, recipient text not null, template text not null,
  payload text default '{}', status text default 'queued', attempts integer default 0,
  sent_at timestamptz, created_at timestamptz default now()
);

create table if not exists public.plugins (
  id bigint generated by default as identity primary key,
  slug text unique not null, name text not null, version text not null,
  status text default 'inactive', manifest text not null, installed_at timestamptz default now()
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_id bigint references public.users(id), action text not null,
  subject_type text not null, subject_id text, detail text default '{}',
  created_at timestamptz default now()
);

create table if not exists public.settings (
  key text primary key, value text not null
);

create index if not exists idx_sessions_user_expires on public.sessions(user_id, expires_at);
create index if not exists idx_entitlements_user on public.entitlements(user_id, expires_at);
create index if not exists idx_orders_user_status on public.orders(user_id, status);
create index if not exists idx_notifications_user_created on public.notifications(user_id, created_at desc);
create index if not exists idx_audit_created on public.audit_logs(created_at desc);

