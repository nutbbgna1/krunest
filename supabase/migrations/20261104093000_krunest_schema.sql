do $$
declare table_name text;
begin
  foreach table_name in array array[
    'users','sessions','tokens','login_attempts','programs','plans','subscriptions','entitlements',
    'orders','payment_slips','receipts','teams','team_members','team_invites','notifications',
    'announcements','email_queue','plugins','audit_logs','settings'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);
  end loop;
end $$;

create or replace function public.krunest_reset_sequences()
returns void language plpgsql security definer set search_path = public as $$
declare table_name text; sequence_name text; max_id bigint;
begin
  foreach table_name in array array['users','subscriptions','orders','payment_slips','receipts','teams','notifications','announcements','email_queue','plugins','audit_logs'] loop
    sequence_name := pg_get_serial_sequence('public.' || table_name, 'id');
    if sequence_name is not null then
      execute format('select coalesce(max(id),0) from public.%I', table_name) into max_id;
      perform setval(sequence_name, greatest(max_id,1), max_id > 0);
    end if;
  end loop;
end;
$$;

revoke all on function public.krunest_reset_sequences() from public, anon, authenticated;
grant execute on function public.krunest_reset_sequences() to service_role;
