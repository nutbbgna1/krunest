create table if not exists public.plugin_records (
  plugin_slug text not null,
  user_id bigint not null references public.users(id) on delete cascade,
  record_key text not null,
  payload text not null,
  updated_at timestamptz default now(),
  primary key (plugin_slug, user_id, record_key)
);

create table if not exists public.plugin_record_events (
  id bigint generated by default as identity primary key,
  plugin_slug text not null,
  user_id bigint not null references public.users(id) on delete cascade,
  record_key text not null,
  action text not null,
  created_at timestamptz default now()
);

alter table public.plugin_records enable row level security;
alter table public.plugin_record_events enable row level security;
